// Deterministic shuffle using seed so each page and section has a unique order
export function getShuffledCategoryAnime(seed) {
    const list = [...categoryAnimeList]
    for (let i = list.length - 1; i > 0; i--) {
        const j = (i * seed + 11) % list.length
        const temp = list[i]
        list[i] = list[j]
        list[j] = temp
    }
    return list
}
